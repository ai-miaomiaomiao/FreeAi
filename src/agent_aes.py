# 逆 S 盒在导入时从正盒反推，省掉再抄一遍 256 个数
_INV_SBOX = [0] * 256
for _i, _v in enumerate(_SBOX):
    _INV_SBOX[_v] = _i
_INV_SBOX = tuple(_INV_SBOX)

_RCON = (0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36)
# fmt: on


def _xtime(a: int) -> int:
    a <<= 1
    return (a ^ 0x1B) & 0xFF if a & 0x100 else a


def _mul(a: int, b: int) -> int:
    """GF(2^8) 乘法，AES 用的不可约多项式是 0x11B。"""
    r = 0
    while b:
        if b & 1:
            r ^= a
        a = _xtime(a)
        b >>= 1
    return r


# 逆列的固定矩阵：14,11,13,9
_MUL9 = [_mul(i, 9) for i in range(256)]
_MUL11 = [_mul(i, 11) for i in range(256)]
_MUL13 = [_mul(i, 13) for i in range(256)]
_MUL14 = [_mul(i, 14) for i in range(256)]


def _expand_key(key: bytes) -> list:
    """AES-128 密钥扩展：16 字节 -> 11 轮 × 16 字节。"""
    if len(key) != 16:
        raise ValueError("AES-128 需要 16 字节密钥，实际 %d" % len(key))
    w = [list(key[i:i + 4]) for i in range(0, 16, 4)]
    for i in range(4, 44):
        t = list(w[i - 1])
        if i % 4 == 0:
            t = t[1:] + t[:1]                       # RotWord
            t = [_SBOX[b] for b in t]               # SubWord
            t[0] ^= _RCON[i // 4 - 1]
        w.append([w[i - 4][j] ^ t[j] for j in range(4)])
    return [sum(w[i:i + 4], []) for i in range(0, 44, 4)]


def _decrypt_block(block: bytes, rk: list) -> bytes:
    s = [b ^ k for b, k in zip(block, rk[10])]

    for rnd in range(9, -1, -1):
        # InvShiftRows
        s = [s[0], s[13], s[10], s[7],
             s[4], s[1], s[14], s[11],
             s[8], s[5], s[2], s[15],
             s[12], s[9], s[6], s[3]]
        # InvSubBytes
        s = [_INV_SBOX[b] for b in s]
        # AddRoundKey
        s = [b ^ k for b, k in zip(s, rk[rnd])]
        if rnd:  # 最后一轮不做 InvMixColumns
            out = []
            for c in range(4):
                a0, a1, a2, a3 = s[c * 4:c * 4 + 4]
                out += [
                    _MUL14[a0] ^ _MUL11[a1] ^ _MUL13[a2] ^ _MUL9[a3],
                    _MUL9[a0] ^ _MUL14[a1] ^ _MUL11[a2] ^ _MUL13[a3],
                    _MUL13[a0] ^ _MUL9[a1] ^ _MUL14[a2] ^ _MUL11[a3],
                    _MUL11[a0] ^ _MUL13[a1] ^ _MUL9[a2] ^ _MUL14[a3],
                ]
            s = out
    return bytes(s)


def aes128_cbc_decrypt(data: bytes, key: bytes, iv: bytes, unpad: bool = True) -> bytes:
    """AES-128-CBC 解密。data 长度必须是 16 的整数倍。"""
    if len(iv) != 16:
        raise ValueError("IV 需要 16 字节，实际 %d" % len(iv))
    if len(data) % 16:
        raise ValueError("密文长度 %d 不是 16 的倍数" % len(data))

    rk = _expand_key(key)
    out = bytearray()
    prev = iv
    for i in range(0, len(data), 16):
        blk = data[i:i + 16]
        dec = _decrypt_block(blk, rk)
        out += bytes(a ^ b for a, b in zip(dec, prev))
        prev = blk

    if unpad and out:
        pad = out[-1]
        if 1 <= pad <= 16 and out[-pad:] == bytes([pad]) * pad:
            del out[-pad:]
    return bytes(out)


def sniff_image(data: bytes) -> str:
    """按文件头猜图片格式，猜不出返回空串。"""
    if data.startswith(b"\xff\xd8\xff"):
        return "jpg"
    if data.startswith(b"\x89PNG"):
        return "png"
    if data.startswith(b"GIF8"):
        return "gif"
    if data.startswith(b"RIFF") and data[8:12] == b"WEBP":
        return "webp"
    if data.startswith(b"BM"):
        return "bmp"
    return ""
